def rep(old, new, count=1):
    global src, n_done
    k = src.count(old)
    assert k == count, f'{k}회 발견 (기대 {count}): {old[:80]!r}'
    src = src.replace(old, new)
    n_done += 1


def rep_block(start, end, new):
    """start 문자열부터 end 문자열 끝까지를 new로 교체"""
    global src, n_done
    i = src.index(start); j = src.index(end, i) + len(end)
    assert src.count(start) == 1
    src = src[:i] + new + src[j:]
    n_done += 1


