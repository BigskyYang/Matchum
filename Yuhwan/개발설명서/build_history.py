for el in list(d.element.body):
    if el.tag != qn('w:sectPr'):
        d.element.body.remove(el)
FONT = 'NanumGothic'


def para(text, bold=None):
    p = d.add_paragraph(style='Normal')
    if bold:
        p.add_run(bold).bold = True
    p.add_run(text)
    return p


def bullet(text, bold=None):
    p = d.add_paragraph(style='Normal')
    p.paragraph_format.left_indent = Pt(10)
    p.add_run('• ')
    if bold:
        p.add_run(bold).bold = True
    p.add_run(text)


def h1(t):
    d.add_paragraph(t, style='Heading 1')


def h2(t):
    p = d.add_paragraph(style='Normal')
    p.paragraph_format.space_before = Pt(8)
    r = p.add_run(t)
    r.bold = True
    r.font.size = Pt(11.5)


def _fmt(cell, width, header):
    tcPr = cell._tc.get_or_add_tcPr()
    w = OxmlElement('w:tcW'); w.set(qn('w:type'), 'dxa'); w.set(qn('w:w'), str(width)); tcPr.append(w)
    mar = OxmlElement('w:tcMar')
    for s in ('top', 'left', 'bottom', 'right'):
        e = OxmlElement(f'w:{s}'); e.set(qn('w:w'), '60'); e.set(qn('w:type'), 'dxa'); mar.append(e)
    tcPr.append(mar)
    b = OxmlElement('w:tcBorders')
    for s in ('top', 'left', 'bottom', 'right'):
        e = OxmlElement(f'w:{s}'); e.set(qn('w:val'), 'single'); e.set(qn('w:sz'), '4'); e.set(qn('w:color'), 'D9D9D9'); b.append(e)
    tcPr.append(b)
    if header:
        s = OxmlElement('w:shd'); s.set(qn('w:fill'), 'E8EEF5'); tcPr.append(s)


def table(rows, widths):
    t = d.add_table(rows=len(rows), cols=len(rows[0]))
    pr = t._tbl.tblPr
    jc = OxmlElement('w:jc'); jc.set(qn('w:val'), 'center'); pr.append(jc)
    lay = OxmlElement('w:tblLayout'); lay.set(qn('w:type'), 'fixed'); pr.append(lay)
    for i, row in enumerate(rows):
        if i == 0:
            trPr = t.rows[0]._tr.get_or_add_trPr()
            trPr.append(OxmlElement('w:cantSplit')); trPr.append(OxmlElement('w:tblHeader'))
        for j, text in enumerate(row):
            c = t.cell(i, j)
            _fmt(c, widths[j], i == 0)
            p = c.paragraphs[0]
            p.paragraph_format.space_after = Pt(1)
            lines = str(text).split('\n')
            for k, line in enumerate(lines):
                r = p.add_run(line)
                r.font.size = Pt(9)
                r.font.name = FONT
                r._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)
                r.bold = i == 0
                if k < len(lines) - 1:
                    r.add_break()
    for j, w in enumerate(widths):
        t.columns[j].width = Twips(w)
    d.add_paragraph()


