FONT = 'NanumGothic'


def para(text, style='Normal', bold_prefix=None):
    p = d.add_paragraph(style=style)
    if bold_prefix:
        r = p.add_run(bold_prefix)
        r.bold = True
    p.add_run(text)
    return p


def bullet(text, bold_prefix=None):
    return para(text, bold_prefix=('• ' + bold_prefix) if bold_prefix else None) if bold_prefix else para('• ' + text)


def h1(text):
    return d.add_paragraph(text, style='Heading 1')


def _cell_fmt(cell, width, header):
    tcPr = cell._tc.get_or_add_tcPr()
    w = OxmlElement('w:tcW'); w.set(qn('w:type'), 'dxa'); w.set(qn('w:w'), str(width)); tcPr.append(w)
    va = OxmlElement('w:vAlign'); va.set(qn('w:val'), 'center'); tcPr.append(va)
    mar = OxmlElement('w:tcMar')
    for side in ('top', 'left', 'bottom', 'right'):
        e = OxmlElement(f'w:{side}'); e.set(qn('w:w'), '60'); e.set(qn('w:type'), 'dxa'); mar.append(e)
    tcPr.append(mar)
    b = OxmlElement('w:tcBorders')
    for side in ('top', 'left', 'bottom', 'right'):
        e = OxmlElement(f'w:{side}'); e.set(qn('w:val'), 'single'); e.set(qn('w:sz'), '4'); e.set(qn('w:color'), 'D9D9D9'); b.append(e)
    tcPr.append(b)
    if header:
        s = OxmlElement('w:shd'); s.set(qn('w:fill'), 'E8EEF5'); tcPr.append(s)


def table(rows, widths):
    """rows[0] = 머리글. widths: dxa 합 약 9,936 (재준님 표와 같은 폭)"""
    t = d.add_table(rows=len(rows), cols=len(rows[0]))
    tblPr = t._tbl.tblPr
    jc = OxmlElement('w:jc'); jc.set(qn('w:val'), 'center'); tblPr.append(jc)
    lay = OxmlElement('w:tblLayout'); lay.set(qn('w:type'), 'fixed'); tblPr.append(lay)
    for i, row in enumerate(rows):
        tr = t.rows[i]._tr
        if i == 0:
            trPr = tr.get_or_add_trPr()
            trPr.append(OxmlElement('w:cantSplit')); trPr.append(OxmlElement('w:tblHeader'))
        for j, text in enumerate(row):
            c = t.cell(i, j)
            _cell_fmt(c, widths[j], i == 0)
            p = c.paragraphs[0]
            p.paragraph_format.space_after = Pt(1)
            lines = str(text).split('\n')
            for k, line in enumerate(lines):
                r = p.add_run(line)
                r.font.size = Pt(9.5)
                r.font.name = FONT
                r._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)
                if i == 0:
                    r.bold = True
                if k < len(lines) - 1:
                    r.add_break()
    for j, w in enumerate(widths):
        t.columns[j].width = docx.shared.Twips(w)
    d.add_paragraph()
    return t


