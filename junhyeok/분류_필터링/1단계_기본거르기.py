# -*- coding: utf-8 -*-
"""
1단계: 기본 거르기
기준: 「영양제_분류_필터링_기준(1104).pdf」 2절, 5-4절 + 11-04 결정

하는 일 (위에서부터 차례로. 한 제품은 처음 걸린 이유 하나로만 기록)
  ① 임산부·수유부 대상 제품 제외
  ② 제품명이 질환을 대상으로 하는 제품 제외 (혈당·혈압·전립선·콜레스테롤·골다공증·갑상선·당뇨 등)
     - 기능성의 "골다공증발생 위험 감소에 도움"은 식약처 인정 문구라 제외 이유가 아님 (제품명만 봄)
  ③ 남은 제품 중 대상 '일반·남성·여성·시니어'는 다음 단계로 (11-04 팀 결정: 웹에서 성별·나이로 대상 맞춤)
  ④ 어린이 제품은 웹 대상이 아니라서 빼지 않고 '보관'만 함
     - 대상은 공통.py의 키워드로 여기서 다시 판별 (11-04 어린이 키워드 보완: 성장·쑥쑥·키튼.
       '아이' 한 글자는 아이오딘(요오드)·아이언(철)·아이케어(눈)·브랜드명과 겹쳐서 쓰지 않음)
  ⑤ (11-05) 판매하지 않을 가능성이 높은 제품 제외 (단종 제품 최대한 거르기)
     - 해외 판매용: 제품명 괄호 안 국가명 (미국·캐나다·일본·호주 등으로 확장. '(브라질산)' 같은 원료 원산지는 제외)
     - (재신고된 옛 제품은 이름만으로는 맛 차이·위탁 제조와 구분이 안 돼서 여기서 빼지 않고,
        8단계 ④ '비슷한 제품'에서 처방이 같은 것이 확인된 경우 가장 최근 신고만 남김)
     - C003에는 '판매 중' 정보가 없어서 단종을 완전히 거를 수는 없음
  (수출 전용, 2021년 이전 제품은 최종본을 만들 때 이미 빠짐)

입력  성분별_영양제_제품목록(최종).xlsx 의 '제품 목록' 시트
출력  1단계_기본거르기.xlsx, 1단계_결과.pkl (일반·남성·여성·시니어, 다음 단계 입력), 1단계_보관.pkl (어린이)
"""
import pandas as pd
from 공통 import out, load_final, target_of, OVERSEAS, new_book, add_sheet, add_criteria_sheet


def main():
    print("[1/3] 최종본 엑셀 읽는 중... (1분 정도)")
    p = load_final()
    n0 = len(p)
    before = p["대상"].copy()
    p["대상"] = p["제품명"].map(target_of)          # 공통.py 키워드로 다시 판별 (키워드를 고치면 바로 반영)
    p["임산부·수유부"] = p["임산부·수유부"].where(p["대상"] != "임산부·수유부", "예")
    n_new_kid = int(((before != "어린이") & (p["대상"] == "어린이")).sum())
    print(f"   어린이 키워드 보완으로 새로 어린이가 된 제품: {n_new_kid:,}개")
    p["빠진 이유"] = ""

    def drop(mask, reason):
        m = mask & (p["빠진 이유"] == "")
        p.loc[m, "빠진 이유"] = reason
        return int(m.sum())

    print("[2/3] 거르는 중...")
    n_preg = drop(p["임산부·수유부"] == "예", "임산부·수유부 대상")
    is_dis = (p["질환 대상 단어"] != "") & (p["빠진 이유"] == "")
    n_dis = drop(is_dis, "")
    p.loc[is_dis, "빠진 이유"] = "질환 대상 제품명 (" + p.loc[is_dis, "질환 대상 단어"] + ")"


    # ⑤ 판매하지 않을 가능성이 높은 제품 (11-05)
    n_over = drop(p["제품명"].str.contains(OVERSEAS, regex=True, na=False), "해외 판매용 표시 (괄호 안 국가명)")
    print(f"   해외 판매용 {n_over}")

    removed = p[p["빠진 이유"] != ""].copy()
    rest = p[p["빠진 이유"] == ""].drop(columns="빠진 이유")
    WEB_TARGETS = ["일반", "남성", "여성", "시니어"]
    keep = rest[rest["대상"].isin(WEB_TARGETS)].reset_index(drop=True)
    hold = rest[~rest["대상"].isin(WEB_TARGETS)].reset_index(drop=True)
    keep.to_pickle(out("1단계_결과.pkl"))
    hold.to_pickle(out("1단계_보관.pkl"))

    # ── 결과 엑셀
    print("[3/3] 결과 엑셀 저장 중... (1~2분, 아무 키도 누르지 마세요)")
    dis_cnt = removed.loc[removed["빠진 이유"].str.startswith("질환"), "질환 대상 단어"].str.replace(" ", "").value_counts()
    keep_cnt = " / ".join(f"{k} {v:,}" for k, v in keep["대상"].value_counts().items())
    lines = [
        ("1단계: 기본 거르기", True), ("", False),
        ("결과", True),
        (f"· 시작 {n0:,}개 → 빠진 제품 {len(removed):,}개 → 남은 제품 {len(rest):,}개", False),
        (f"· 다음 단계로 (일반·남성·여성·시니어): {len(keep):,}개 ({keep_cnt})", False),
        (f"· 보관 (어린이, 웹 대상 아님): {len(hold):,}개 (11-04 어린이 키워드 보완으로 {n_new_kid:,}개 추가)", False),
        ("", False), ("빠진 이유", True),
        (f"· 임산부·수유부 대상: {n_preg:,}개", False),
        (f"· 질환 대상 제품명: {n_dis:,}개 ({' / '.join(f'{k} {v:,}' for k, v in dis_cnt.items())})", False),
        ("· 기능성의 '골다공증발생 위험 감소에 도움'은 식약처 인정 문구라 제외 이유로 쓰지 않음 (제품명에 '골다공증'을 내세운 경우만 제외)", False),
        (f"· 판매하지 않을 가능성이 높은 제품 (11-05): 해외 판매용 {n_over:,}", False),
        ("   - 재신고된 옛 제품은 8단계 '비슷한 제품'에서 가장 최근 신고만 남기는 방식으로 정리", False),
        ("   - C003에는 '판매 중' 정보가 없어 단종을 완전히 거를 수는 없음", False),
        ("", False), ("참고", True),
        ("· 수출 전용·해외 판매 의심, 2021년 이전 신고 제품은 최종본을 만들 때 이미 빠짐", False),
        ("· 같은 결과를 다시 만들려면: python 1단계_기본거르기.py", False),
    ]
    wb = new_book(lines)
    add_criteria_sheet(wb, {
        "식품영양성분DB": "적용 완료 (최종본에서 보조 파일로 분리)",
        "기능성 문구만 있는 제품도": "적용 완료 (최종본)",
        "원재료·섭취방법·기준규격은": "적용 완료 (최종본)",
        "2022년 이후 신고": "적용 완료 (최종본)",
        "제품명에 '수출'": "적용 완료 (최종본 제외 목록)",
        "대상 판별": f"적용 완료 (일반·남성·여성·시니어 {len(keep):,} / 어린이 보관 {len(hold):,})",
        "임산부·수유부": f"적용 완료 ({n_preg:,}개 뺌)",
        "제품명이 질환을": f"적용 완료 ({n_dis:,}개 뺌)",
        "일반·전문 의약품": "적용 완료 (C003은 건강기능식품 신고 자료, 의약품 0개)",
    })
    w = [18, 32, 20, 11, 10, 8, 8, 10, 8, 30, 60, 40, 30, 40, 40]
    add_sheet(wb, f"남은 제품 ({len(keep):,})", keep, w)
    add_sheet(wb, f"보관 어린이 ({len(hold):,})", hold, w)
    cols = ["빠진 이유", "품목제조신고번호", "제품명", "업체명", "신고일자", "대상", "함께 든 가이드 성분", "기능성"]
    add_sheet(wb, f"빠진 제품 ({len(removed):,})", removed[cols].sort_values("빠진 이유"), [30, 18, 40, 20, 11, 10, 30, 60])
    wb.save(out("1단계_기본거르기.xlsx"))
    print(f"1단계 완료: {n0:,} → 빠짐 {len(removed):,} (임산부 {n_preg} · 질환 {n_dis} · 해외 {n_over}) → 다음 단계 {len(keep):,} ({keep_cnt}) / 어린이 보관 {len(hold):,}")


if __name__ == "__main__":
    main()
